/** Whether an icon's name has a word of the category: one of its words (`_` between them), or the first words of it, starts with
 * one of the category's (`account_balance` is in `business` by `account_balance`; `home_work` in `home` by `home`).
 * @param {string} name @param {keyof typeof ICON_CATEGORIES} category */
export function inIconCategory(name, category) {
  const words = ICON_CATEGORIES[category];
  if (!words) return false;
  const parts = name.split('_');
  return words.some((w) => {
    const w_ = w.split('_');
    return w_.every((x, i) => parts[i] === x) || (w_.length === 1 && parts.includes(w));
  });
}

/** The names that match what is typed (searchIconNames) and are in the category (all of them without one).
 * @param {string[]} names @param {string} query @param {keyof typeof ICON_CATEGORIES | ''} category @returns {string[]} */
export function filterIconNames(names, query, category) {
  const found = query.trim() ? searchIconNames(names, query) : names;
  return category ? found.filter((n) => inIconCategory(n, category)) : found;
}
