/** Phosphor's weight suffix: a `-fill` name is the filled icon of its regular name. @param {string} name */
const regular = (name) => (name.endsWith('-fill') ? name.slice(0, -5) : name);

/** The Material Symbols name of a stored Phosphor icon name (`map-pin` → `location_on`), or undefined for a name that is already Material's or unknown.
 * @param {string} name @returns {{ name: string, fill: boolean, closest: boolean } | undefined} */
export function materialNameOf(name) {
  const base = regular(name);
  const e = MAP[base];
  if (!e) return undefined;
  return { name: typeof e === 'string' ? e : e.name, fill: base !== name, closest: typeof e !== 'string' };
}

/** Every entry: Phosphor name, Material name, closest. @returns {{ phosphor: string, material: string, closest: boolean }[]} */
export function iconMapEntries() {
  return Object.entries(MAP).map(([phosphor, e]) => ({
    phosphor,
    material: typeof e === 'string' ? e : e.name,
    closest: typeof e !== 'string',
  }));
}
